
-- Objeto: TIPO_COMBUSTIBLE

SET DEFINE OFF;

CREATE TABLE TIPO_COMBUSTIBLE (
    ID_COMBUSTIBLE    NUMBER(4) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CODIGO            VARCHAR2(12 CHAR) NOT NULL,
    NOMBRE            VARCHAR2(50 CHAR) NOT NULL,
    ESTADO            CHAR(1 CHAR) DEFAULT 'A' NOT NULL,
    CONSTRAINT PK_TIPO_COMBUSTIBLE PRIMARY KEY (ID_COMBUSTIBLE),
    CONSTRAINT UQ_TIPO_COMBUSTIBLE_COD UNIQUE (CODIGO),
    CONSTRAINT CK_TIPO_COMBUSTIBLE_COD CHECK (CODIGO IN ('GASOLINA', 'DIESEL')),
    CONSTRAINT CK_TIPO_COMBUSTIBLE_EST CHECK (ESTADO IN ('A', 'I'))
);


