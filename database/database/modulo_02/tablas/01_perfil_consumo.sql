-- Tabla: PERFIL_CONSUMO. 
 ID_PERFIL NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
 CATEGORIA VARCHAR2(30 CHAR) NOT NULL,
 CILINDRADA_MIN NUMBER(6) NOT NULL,
 CILINDRADA_MAX NUMBER(6) NOT NULL,
 CONSUMO_L_100KM NUMBER(7,2) NOT NULL,
 VIGENCIA_DESDE DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
 CONSTRAINT PK_PERFIL_CONSUMO PRIMARY KEY (ID_PERFIL),
 CONSTRAINT CK_PERFIL_RANGO CHECK (CILINDRADA_MIN > 0 AND CILINDRADA_MAX >= CILINDRADA_MIN),
 CONSTRAINT CK_PERFIL_CONSUMO CHECK (CONSUMO_L_100KM > 0)
);


