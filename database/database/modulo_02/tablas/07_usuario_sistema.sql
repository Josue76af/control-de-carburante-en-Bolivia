-- Tabla: USUARIO_SISTEMA. 
CREATE TABLE USUARIO_SISTEMA (
 ID_USUARIO NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
 USUARIO VARCHAR2(60 CHAR) NOT NULL,
 NOMBRE_COMPLETO VARCHAR2(150 CHAR) NOT NULL,
 HASH_CREDENCIAL VARCHAR2(255 CHAR) NOT NULL,
 ESTADO VARCHAR2(15 CHAR) DEFAULT 'ACTIVO' NOT NULL,
 FECHA_REGISTRO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT PK_USUARIO PRIMARY KEY (ID_USUARIO),
 CONSTRAINT UQ_USUARIO UNIQUE (USUARIO),
 CONSTRAINT CK_USUARIO_EST CHECK (ESTADO IN ('ACTIVO','INACTIVO','BLOQUEADO'))
);


