-- Tabla: USUARIO_ROL. 
CREATE TABLE USUARIO_ROL (
 ID_USUARIO NUMBER(12) NOT NULL,
 ID_ROL NUMBER(6) NOT NULL,
 FECHA_ASIGNACION TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT PK_USUARIO_ROL PRIMARY KEY (ID_USUARIO,ID_ROL),
 CONSTRAINT FK_UR_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO_SISTEMA(ID_USUARIO),
 CONSTRAINT FK_UR_ROL FOREIGN KEY (ID_ROL) REFERENCES ROL(ID_ROL)
);

CREATE INDEX IX_M2_USUARIO_ROL_ROL ON USUARIO_ROL(ID_ROL);
