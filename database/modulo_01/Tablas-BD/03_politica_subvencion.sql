
-- Objeto: POLITICA_SUBVENCION

SET DEFINE OFF;

CREATE TABLE POLITICA_SUBVENCION (
    ID_POLITICA           NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    VIGENCIA_DESDE        DATE NOT NULL,
    VIGENCIA_HASTA        DATE,
    LITROS_SEMANALES      NUMBER(8,2) NOT NULL,
    MAX_VEHICULOS         NUMBER(3) NOT NULL,
    MOTIVO                VARCHAR2(250 CHAR) NOT NULL,
    FECHA_REGISTRO        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_POLITICA_SUBVENCION PRIMARY KEY (ID_POLITICA),
    CONSTRAINT UQ_POLITICA_DESDE UNIQUE (VIGENCIA_DESDE),
    CONSTRAINT CK_POLITICA_LITROS CHECK (LITROS_SEMANALES > 0),
    CONSTRAINT CK_POLITICA_MAX CHECK (MAX_VEHICULOS BETWEEN 1 AND 999),
    CONSTRAINT CK_POLITICA_FECHAS CHECK
        (VIGENCIA_HASTA IS NULL OR VIGENCIA_HASTA > VIGENCIA_DESDE)
);


