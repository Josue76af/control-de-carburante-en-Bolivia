/* ---------------------------------------------------------------------
   1. VEHICULO
   Cada vehículo pertenece a una sola persona. La misma persona puede
   registrar como máximo dos vehículos (auto y/o moto).
   --------------------------------------------------------------------- */
CREATE TABLE VEHICULO (
    ID_VEHICULO          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_PERSONA           NUMBER NOT NULL,
    ID_COMBUSTIBLE       NUMBER NOT NULL,
    PLACA                VARCHAR2(15 CHAR) NOT NULL,
    NUMERO_RUAT          VARCHAR2(30 CHAR),
    TIPO_VEHICULO        VARCHAR2(10 CHAR) NOT NULL,
    MARCA                VARCHAR2(60 CHAR),
    MODELO               VARCHAR2(60 CHAR),
    ANIO_FABRICACION     NUMBER(4),
    CAPACIDAD_TANQUE_L   NUMBER(7,2) NOT NULL,
    ESTADO               VARCHAR2(12 CHAR) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_REGISTRO       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_ACTUALIZACION  TIMESTAMP,

    CONSTRAINT PK_VEHICULO PRIMARY KEY (ID_VEHICULO),
    CONSTRAINT UK_VEHICULO_PLACA UNIQUE (PLACA),
    CONSTRAINT FK_VEHICULO_PERSONA FOREIGN KEY (ID_PERSONA)
        REFERENCES PERSONA (ID_PERSONA),
    CONSTRAINT FK_VEHICULO_COMBUSTIBLE FOREIGN KEY (ID_COMBUSTIBLE)
        REFERENCES TIPO_COMBUSTIBLE (ID_COMBUSTIBLE),
    CONSTRAINT CK_VEHICULO_TIPO CHECK (TIPO_VEHICULO IN ('AUTO', 'MOTO')),
    CONSTRAINT CK_VEHICULO_CAPACIDAD CHECK (CAPACIDAD_TANQUE_L > 0),
    CONSTRAINT CK_VEHICULO_ANIO CHECK (
        ANIO_FABRICACION IS NULL OR ANIO_FABRICACION BETWEEN 1950 AND 2100
    ),
    CONSTRAINT CK_VEHICULO_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO', 'BLOQUEADO'))
);
CREATE INDEX IX_VEHICULO_PERSONA ON VEHICULO (ID_PERSONA);
CREATE INDEX IX_VEHICULO_COMBUSTIBLE ON VEHICULO (ID_COMBUSTIBLE);