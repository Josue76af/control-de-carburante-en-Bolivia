
CREATE TABLE BIOMETRIA (
    ID_BIOMETRIA          NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_PERSONA            NUMBER NOT NULL,
    DEDO                  VARCHAR2(20 CHAR) DEFAULT 'NO_ESPECIFICADO' NOT NULL,
    PLANTILLA_CIFRADA     BLOB NOT NULL,
    ALGORITMO             VARCHAR2(60 CHAR) NOT NULL,
    VERSION_PLANTILLA     VARCHAR2(30 CHAR),
    PROVEEDOR_DISPOSITIVO VARCHAR2(80 CHAR),
    ESTADO                VARCHAR2(12 CHAR) DEFAULT 'ACTIVA' NOT NULL,
    FECHA_ENROLAMIENTO    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_REVOCACION      TIMESTAMP,

    CONSTRAINT PK_BIOMETRIA PRIMARY KEY (ID_BIOMETRIA),
    CONSTRAINT FK_BIOMETRIA_PERSONA FOREIGN KEY (ID_PERSONA)
        REFERENCES PERSONA (ID_PERSONA),
    CONSTRAINT CK_BIOMETRIA_DEDO CHECK (DEDO IN (
        'PULGAR_DER', 'INDICE_DER', 'MEDIO_DER', 'ANULAR_DER', 'MENIQUE_DER',
        'PULGAR_IZQ', 'INDICE_IZQ', 'MEDIO_IZQ', 'ANULAR_IZQ', 'MENIQUE_IZQ',
        'NO_ESPECIFICADO'
    )),
    CONSTRAINT CK_BIOMETRIA_ESTADO CHECK (ESTADO IN ('ACTIVA', 'REVOCADA', 'INACTIVA'))
);
CREATE INDEX IX_BIOMETRIA_PERSONA ON BIOMETRIA (ID_PERSONA);
CREATE UNIQUE INDEX UK_BIOMETRIA_ACTIVA ON BIOMETRIA (
    CASE WHEN ESTADO = 'ACTIVA' THEN ID_PERSONA END,
    CASE WHEN ESTADO = 'ACTIVA' THEN DEDO END
);
