CREATE TABLE CUPO_SEMANAL (
    ID_CUPO NUMBER(12)
        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_PERSONA NUMBER(12) NOT NULL,
    ID_POLITICA NUMBER(12) NOT NULL,
    FECHA_INICIO_SEMANA DATE NOT NULL,
    LITROS_ASIGNADOS NUMBER(8,2) NOT NULL,
    LITROS_CONSUMIDOS NUMBER(8,2) DEFAULT 0 NOT NULL,

    CONSTRAINT PK_CUPO_SEMANAL
        PRIMARY KEY (ID_CUPO),

    CONSTRAINT FK_CUPO_PERSONA
        FOREIGN KEY (ID_PERSONA)
        REFERENCES PERSONA(ID_PERSONA),

    CONSTRAINT FK_CUPO_POLITICA
        FOREIGN KEY (ID_POLITICA)
        REFERENCES POLITICA_SUBVENCION(ID_POLITICA),

    CONSTRAINT UQ_CUPO_PERSONA_SEMANA
        UNIQUE (ID_PERSONA, FECHA_INICIO_SEMANA),

    CONSTRAINT CK_CUPO_ASIGNADOS
        CHECK (LITROS_ASIGNADOS > 0),

    CONSTRAINT CK_CUPO_CONSUMIDOS
        CHECK (
            LITROS_CONSUMIDOS >= 0
            AND LITROS_CONSUMIDOS <= LITROS_ASIGNADOS
        )
);

CREATE INDEX IX_CUPO_POLITICA
ON CUPO_SEMANAL(ID_POLITICA);