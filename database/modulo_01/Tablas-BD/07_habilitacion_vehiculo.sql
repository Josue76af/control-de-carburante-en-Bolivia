CREATE TABLE HABILITACION_VEHICULO (
    ID_HABILITACION NUMBER(12)
        GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_PERSONA NUMBER(12) NOT NULL,
    ID_VEHICULO NUMBER(12) NOT NULL,
    HABILITADO_DESDE TIMESTAMP
        DEFAULT SYSTIMESTAMP NOT NULL,
    HABILITADO_HASTA TIMESTAMP,
    MOTIVO VARCHAR2(200 CHAR),

    CONSTRAINT PK_HABILITACION_VEHICULO
        PRIMARY KEY (ID_HABILITACION),

    CONSTRAINT FK_HABILITACION_PERSONA
        FOREIGN KEY (ID_PERSONA)
        REFERENCES PERSONA(ID_PERSONA),

    CONSTRAINT FK_HABILITACION_VEHICULO
        FOREIGN KEY (ID_VEHICULO)
        REFERENCES VEHICULO(ID_VEHICULO),

    CONSTRAINT CK_HABILITACION_FECHAS
        CHECK (
            HABILITADO_HASTA IS NULL
            OR HABILITADO_HASTA > HABILITADO_DESDE
        )
);

CREATE UNIQUE INDEX UX_HAB_VEHICULO_ACTIVO
ON HABILITACION_VEHICULO (
    CASE
        WHEN HABILITADO_HASTA IS NULL
        THEN ID_VEHICULO
    END
);

CREATE INDEX IX_HAB_PERSONA_FECHAS
ON HABILITACION_VEHICULO (
    ID_PERSONA,
    HABILITADO_DESDE,
    HABILITADO_HASTA
);