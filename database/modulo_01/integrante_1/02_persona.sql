
-- Objeto: PERSONA

SET DEFINE OFF;

CREATE TABLE PERSONA (
    ID_PERSONA        NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CI                VARCHAR2(25 CHAR) NOT NULL,
    NOMBRES           VARCHAR2(100 CHAR) NOT NULL,
    APELLIDOS         VARCHAR2(120 CHAR) NOT NULL,
    TELEFONO          VARCHAR2(25 CHAR),
    ESTADO            VARCHAR2(15 CHAR) DEFAULT 'ACTIVO' NOT NULL,
    FECHA_REGISTRO    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PERSONA PRIMARY KEY (ID_PERSONA),
    CONSTRAINT UQ_PERSONA_CI UNIQUE (CI),
    CONSTRAINT CK_PERSONA_ESTADO CHECK (ESTADO IN ('ACTIVO', 'INACTIVO', 'BLOQUEADO'))
);


