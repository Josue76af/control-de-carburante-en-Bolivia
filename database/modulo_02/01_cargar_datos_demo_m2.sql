-- Ejecutar como SCRIPT con F5 DESPUES de 00_instalar_modulo_02.sql.
-- Inserta 20 estaciones ficticias, 2 combustibles, 4 precios, 40 tanques,
-- 20 surtidores, 40 mangueras y 40 recepciones, entre otros registros.
-- Idempotente para los registros con codigo DEMO. NO usar informacion personal real.
-- Precios de ejemplo, NO precios oficiales de Bolivia.
-- HASH_CREDENCIAL contiene marcador de prueba: NO permite autenticacion real.
SET DEFINE OFF;
SET SERVEROUTPUT ON;
WHENEVER SQLERROR EXIT SQL.SQLCODE ROLLBACK;
DECLARE
    V_GAS        NUMBER;
    V_DIE        NUMBER;
    V_OPERADOR   NUMBER;
    V_SUPERVISOR NUMBER;
    V_ESTACION   NUMBER;
    V_SURTIDOR   NUMBER;
    V_TG         NUMBER;
    V_TD         NUMBER;
    V_LG         NUMBER;
    V_LD         NUMBER;
    V_ID_ROL     NUMBER;
    V_EXISTE     NUMBER;
    V_CODIGO     VARCHAR2(30);
    V_DOCUMENTO  VARCHAR2(80);
    PROCEDURE P_PRECIO(P_COMB NUMBER, P_TARIFA VARCHAR2, P_VAL NUMBER) IS
    BEGIN
        MERGE INTO PRECIO_COMBUSTIBLE T
        USING (SELECT P_COMB AS ID_COMBUSTIBLE, P_TARIFA AS TARIFA FROM DUAL) S
        ON (T.ID_COMBUSTIBLE = S.ID_COMBUSTIBLE AND T.TARIFA = S.TARIFA
            AND T.VIGENCIA_DESDE = DATE '2026-01-01')
        WHEN NOT MATCHED THEN INSERT
          (ID_COMBUSTIBLE, TARIFA, PRECIO_LITRO, VIGENCIA_DESDE)
          VALUES (S.ID_COMBUSTIBLE, S.TARIFA, P_VAL, DATE '2026-01-01');
    END;
    PROCEDURE P_PERFIL(P_CAT VARCHAR2, P_MIN NUMBER, P_MAX NUMBER, P_CONS NUMBER) IS
    BEGIN
        MERGE INTO PERFIL_CONSUMO T
        USING (SELECT P_CAT AS CATEGORIA FROM DUAL) S
           ON (T.CATEGORIA = S.CATEGORIA AND T.VIGENCIA_DESDE = DATE '2026-01-01')
        WHEN NOT MATCHED THEN INSERT
          (CATEGORIA, CILINDRADA_MIN, CILINDRADA_MAX, CONSUMO_L_100KM, VIGENCIA_DESDE)
          VALUES (S.CATEGORIA, P_MIN, P_MAX, P_CONS, DATE '2026-01-01');
    END;
BEGIN
    MERGE INTO TIPO_COMBUSTIBLE T USING (SELECT 'GASOLINA' CODIGO FROM DUAL) S
      ON (T.CODIGO = S.CODIGO)
    WHEN NOT MATCHED THEN INSERT (CODIGO, NOMBRE, ESTADO)
      VALUES (S.CODIGO, 'Gasolina (catalogo DEMO)', 'A');
    MERGE INTO TIPO_COMBUSTIBLE T USING (SELECT 'DIESEL' CODIGO FROM DUAL) S
      ON (T.CODIGO = S.CODIGO)
    WHEN NOT MATCHED THEN INSERT (CODIGO, NOMBRE, ESTADO)
      VALUES (S.CODIGO, 'Diesel (catalogo DEMO)', 'A');
    SELECT ID_COMBUSTIBLE INTO V_GAS FROM TIPO_COMBUSTIBLE WHERE CODIGO='GASOLINA';
    SELECT ID_COMBUSTIBLE INTO V_DIE FROM TIPO_COMBUSTIBLE WHERE CODIGO='DIESEL';

    P_PRECIO(V_GAS, 'SUBVENCIONADO', 3.70);
    P_PRECIO(V_GAS, 'INTERNACIONAL', 8.00);
    P_PRECIO(V_DIE, 'SUBVENCIONADO', 3.50);
    P_PRECIO(V_DIE, 'INTERNACIONAL', 8.50);
    P_PERFIL('AUTO_BAJA', 800, 1399, 6.20);
    P_PERFIL('AUTO_MEDIA', 1400, 2499, 8.80);
    P_PERFIL('AUTO_ALTA', 2500, 8000, 13.50);

    MERGE INTO ROL T USING (SELECT 'OPERADOR' NOMBRE FROM DUAL) S ON(T.NOMBRE=S.NOMBRE)
    WHEN NOT MATCHED THEN INSERT(NOMBRE,DESCRIPCION)
    VALUES(S.NOMBRE,'Operador de surtidor - ejemplo');
    MERGE INTO ROL T USING (SELECT 'SUPERVISOR_REGIONAL' NOMBRE FROM DUAL) S ON(T.NOMBRE=S.NOMBRE)
    WHEN NOT MATCHED THEN INSERT(NOMBRE,DESCRIPCION)
    VALUES(S.NOMBRE,'Supervisor de estaciones - ejemplo');
    MERGE INTO ROL T USING (SELECT 'AUDITOR' NOMBRE FROM DUAL) S ON(T.NOMBRE=S.NOMBRE)
    WHEN NOT MATCHED THEN INSERT(NOMBRE,DESCRIPCION)
    VALUES(S.NOMBRE,'Consultas de auditoria - ejemplo');
    MERGE INTO ROL T USING (SELECT 'ADMIN_CENTRAL' NOMBRE FROM DUAL) S ON(T.NOMBRE=S.NOMBRE)
    WHEN NOT MATCHED THEN INSERT(NOMBRE,DESCRIPCION)
    VALUES(S.NOMBRE,'Administrador central - ejemplo');

    MERGE INTO USUARIO_SISTEMA T USING (SELECT 'demo_operador_m2' USUARIO FROM DUAL) S
    ON (T.USUARIO=S.USUARIO)
    WHEN NOT MATCHED THEN INSERT(USUARIO,NOMBRE_COMPLETO,HASH_CREDENCIAL)
    VALUES(S.USUARIO,'Operador sintetico M2','NO_AUTENTICAR_DEMO');
    MERGE INTO USUARIO_SISTEMA T USING (SELECT 'demo_supervisor_m2' USUARIO FROM DUAL) S
    ON (T.USUARIO=S.USUARIO)
    WHEN NOT MATCHED THEN INSERT(USUARIO,NOMBRE_COMPLETO,HASH_CREDENCIAL)
    VALUES(S.USUARIO,'Supervisor sintetico M2','NO_AUTENTICAR_DEMO');
    SELECT ID_USUARIO INTO V_OPERADOR FROM USUARIO_SISTEMA WHERE USUARIO='demo_operador_m2';
    SELECT ID_USUARIO INTO V_SUPERVISOR FROM USUARIO_SISTEMA WHERE USUARIO='demo_supervisor_m2';

    SELECT ID_ROL INTO V_ID_ROL FROM ROL WHERE NOMBRE='OPERADOR';
    MERGE INTO USUARIO_ROL T USING (SELECT V_OPERADOR AS ID_USUARIO, V_ID_ROL AS ID_ROL FROM DUAL) S
    ON(T.ID_USUARIO=S.ID_USUARIO AND T.ID_ROL=S.ID_ROL)
    WHEN NOT MATCHED THEN INSERT(ID_USUARIO,ID_ROL) VALUES(S.ID_USUARIO,S.ID_ROL);
    SELECT ID_ROL INTO V_ID_ROL FROM ROL WHERE NOMBRE='SUPERVISOR_REGIONAL';
    MERGE INTO USUARIO_ROL T USING (SELECT V_SUPERVISOR AS ID_USUARIO, V_ID_ROL AS ID_ROL FROM DUAL) S
    ON(T.ID_USUARIO=S.ID_USUARIO AND T.ID_ROL=S.ID_ROL)
    WHEN NOT MATCHED THEN INSERT(ID_USUARIO,ID_ROL) VALUES(S.ID_USUARIO,S.ID_ROL);

    MERGE INTO LOTE_COMBUSTIBLE T USING (SELECT 'DEMO-LOTE-G' CODIGO_LOTE FROM DUAL) S
    ON (T.CODIGO_LOTE=S.CODIGO_LOTE)
    WHEN NOT MATCHED THEN INSERT(ID_COMBUSTIBLE,CODIGO_LOTE,PROVEEDOR,FECHA_LOTE)
    VALUES(V_GAS,S.CODIGO_LOTE,'PROVEEDOR SINTETICO',DATE '2026-01-01');
    MERGE INTO LOTE_COMBUSTIBLE T USING (SELECT 'DEMO-LOTE-D' CODIGO_LOTE FROM DUAL) S
    ON (T.CODIGO_LOTE=S.CODIGO_LOTE)
    WHEN NOT MATCHED THEN INSERT(ID_COMBUSTIBLE,CODIGO_LOTE,PROVEEDOR,FECHA_LOTE)
    VALUES(V_DIE,S.CODIGO_LOTE,'PROVEEDOR SINTETICO',DATE '2026-01-01');
    SELECT ID_LOTE INTO V_LG FROM LOTE_COMBUSTIBLE WHERE CODIGO_LOTE='DEMO-LOTE-G';
    SELECT ID_LOTE INTO V_LD FROM LOTE_COMBUSTIBLE WHERE CODIGO_LOTE='DEMO-LOTE-D';

    FOR I IN 1..20 LOOP
        V_CODIGO := 'DEMO-ES-' || LPAD(TO_CHAR(I),2,'0');
        MERGE INTO ESTACION_SERVICIO T
        USING (SELECT V_CODIGO AS CODIGO FROM DUAL) S ON (T.CODIGO=S.CODIGO)
        WHEN NOT MATCHED THEN INSERT
           (CODIGO,NOMBRE,DEPARTAMENTO,MUNICIPIO,DIRECCION,LATITUD,LONGITUD)
        VALUES
           (S.CODIGO,'Estacion sintetica '||LPAD(TO_CHAR(I),2,'0'),
            'Cochabamba','Cochabamba','Direccion de ejemplo NO REAL',
            -17.4000000 + I * 0.002, -66.1600000 + I * 0.002);
        SELECT ID_ESTACION INTO V_ESTACION FROM ESTACION_SERVICIO WHERE CODIGO=V_CODIGO;

        MERGE INTO SURTIDOR T
        USING (SELECT V_ESTACION AS ID_ESTACION, 'S01' AS CODIGO FROM DUAL) S
        ON (T.ID_ESTACION=S.ID_ESTACION AND T.CODIGO=S.CODIGO)
        WHEN NOT MATCHED THEN INSERT(ID_ESTACION,CODIGO)
        VALUES(S.ID_ESTACION,S.CODIGO);
        SELECT ID_SURTIDOR INTO V_SURTIDOR FROM SURTIDOR
        WHERE ID_ESTACION=V_ESTACION AND CODIGO='S01';

        MERGE INTO TANQUE_ESTACION T
        USING (SELECT V_ESTACION AS ID_ESTACION, 'TG01' AS CODIGO FROM DUAL) S
        ON(T.ID_ESTACION=S.ID_ESTACION AND T.CODIGO=S.CODIGO)
        WHEN NOT MATCHED THEN INSERT(ID_ESTACION,ID_COMBUSTIBLE,CODIGO,CAPACIDAD_MAX_L)
        VALUES(S.ID_ESTACION,V_GAS,S.CODIGO,12000);
        MERGE INTO TANQUE_ESTACION T
        USING (SELECT V_ESTACION AS ID_ESTACION, 'TD01' AS CODIGO FROM DUAL) S
        ON(T.ID_ESTACION=S.ID_ESTACION AND T.CODIGO=S.CODIGO)
        WHEN NOT MATCHED THEN INSERT(ID_ESTACION,ID_COMBUSTIBLE,CODIGO,CAPACIDAD_MAX_L)
        VALUES(S.ID_ESTACION,V_DIE,S.CODIGO,12000);
        SELECT ID_TANQUE INTO V_TG FROM TANQUE_ESTACION
        WHERE ID_ESTACION=V_ESTACION AND CODIGO='TG01';
        SELECT ID_TANQUE INTO V_TD FROM TANQUE_ESTACION
        WHERE ID_ESTACION=V_ESTACION AND CODIGO='TD01';

        MERGE INTO MANGUERA T
        USING (SELECT V_SURTIDOR AS ID_SURTIDOR, 'MG01' AS CODIGO FROM DUAL) S
        ON(T.ID_SURTIDOR=S.ID_SURTIDOR AND T.CODIGO=S.CODIGO)
        WHEN NOT MATCHED THEN INSERT(ID_SURTIDOR,ID_TANQUE,CODIGO)
        VALUES(S.ID_SURTIDOR,V_TG,S.CODIGO);
        MERGE INTO MANGUERA T
        USING (SELECT V_SURTIDOR AS ID_SURTIDOR, 'MD01' AS CODIGO FROM DUAL) S
        ON(T.ID_SURTIDOR=S.ID_SURTIDOR AND T.CODIGO=S.CODIGO)
        WHEN NOT MATCHED THEN INSERT(ID_SURTIDOR,ID_TANQUE,CODIGO)
        VALUES(S.ID_SURTIDOR,V_TD,S.CODIGO);

        MERGE INTO ASIGNACION_ESTACION T
        USING (SELECT V_OPERADOR AS ID_USUARIO, V_ESTACION AS ID_ESTACION FROM DUAL) S
        ON(T.ID_USUARIO=S.ID_USUARIO AND T.ID_ESTACION=S.ID_ESTACION
           AND T.FECHA_INICIO=DATE '2026-01-01')
        WHEN NOT MATCHED THEN INSERT(ID_USUARIO,ID_ESTACION,FECHA_INICIO)
        VALUES(S.ID_USUARIO,S.ID_ESTACION,DATE '2026-01-01');

        V_DOCUMENTO := 'DEMO-REC-' || LPAD(TO_CHAR(I),2,'0') || '-G';
        SELECT COUNT(*) INTO V_EXISTE FROM RECEPCION_COMBUSTIBLE
        WHERE NUMERO_DOCUMENTO=V_DOCUMENTO;
        IF V_EXISTE=0 THEN
           PRC_M2_REGISTRAR_RECEPCION(V_LG,V_TG,V_OPERADOR,5000,V_DOCUMENTO);
        END IF;
        V_DOCUMENTO := 'DEMO-REC-' || LPAD(TO_CHAR(I),2,'0') || '-D';
        SELECT COUNT(*) INTO V_EXISTE FROM RECEPCION_COMBUSTIBLE
        WHERE NUMERO_DOCUMENTO=V_DOCUMENTO;
        IF V_EXISTE=0 THEN
           PRC_M2_REGISTRAR_RECEPCION(V_LD,V_TD,V_OPERADOR,5000,V_DOCUMENTO);
        END IF;
    END LOOP;
    COMMIT;
    DBMS_OUTPUT.PUT_LINE('Demo M2: 20 estaciones ficticias, 40 tanques y 40 recepciones disponibles.');
EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
END;
