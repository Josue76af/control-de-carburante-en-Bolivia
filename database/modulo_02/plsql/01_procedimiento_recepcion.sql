-- MODULO 02 - Recepcion transaccional de combustible.
-- Invocar desde SQL Developer o backend. El procedimiento NO hace COMMIT.
-- Exige lote de combustible compatible, operador asignado y capacidad disponible.
-- Esta rutina se usa para la DEMO, pero debe recibir pruebas de concurrencia y seguridad.
CREATE OR REPLACE PROCEDURE PRC_M2_REGISTRAR_RECEPCION (
    P_ID_LOTE       IN RECEPCION_COMBUSTIBLE.ID_LOTE%TYPE,
    P_ID_TANQUE     IN RECEPCION_COMBUSTIBLE.ID_TANQUE%TYPE,
    P_ID_USUARIO    IN RECEPCION_COMBUSTIBLE.ID_USUARIO%TYPE,
    P_LITROS        IN RECEPCION_COMBUSTIBLE.LITROS_RECIBIDOS%TYPE,
    P_NUM_DOCUMENTO IN RECEPCION_COMBUSTIBLE.NUMERO_DOCUMENTO%TYPE
)
AS
    V_COMB_LOTE     LOTE_COMBUSTIBLE.ID_COMBUSTIBLE%TYPE;
    V_COMB_TANQUE   TANQUE_ESTACION.ID_COMBUSTIBLE%TYPE;
    V_SALDO         TANQUE_ESTACION.SALDO_ESTIMADO_L%TYPE;
    V_CAPACIDAD     TANQUE_ESTACION.CAPACIDAD_MAX_L%TYPE;
    V_ID_ESTACION   TANQUE_ESTACION.ID_ESTACION%TYPE;
    V_PERMISOS      NUMBER;
BEGIN
    IF P_LITROS IS NULL OR P_LITROS <= 0 THEN
        RAISE_APPLICATION_ERROR(-20601, 'Los litros recibidos deben ser positivos');
    END IF;
    IF P_NUM_DOCUMENTO IS NULL OR LENGTH(TRIM(P_NUM_DOCUMENTO)) = 0 THEN
        RAISE_APPLICATION_ERROR(-20607, 'El numero de documento es obligatorio');
    END IF;

    -- Bloquea tanque durante lectura y actualizacion, evitando sobrellenados concurrentes.
    SELECT ID_COMBUSTIBLE, SALDO_ESTIMADO_L, CAPACIDAD_MAX_L, ID_ESTACION
      INTO V_COMB_TANQUE, V_SALDO, V_CAPACIDAD, V_ID_ESTACION
      FROM TANQUE_ESTACION
     WHERE ID_TANQUE = P_ID_TANQUE
     FOR UPDATE;

    SELECT ID_COMBUSTIBLE INTO V_COMB_LOTE
      FROM LOTE_COMBUSTIBLE
     WHERE ID_LOTE = P_ID_LOTE;

    IF V_COMB_LOTE <> V_COMB_TANQUE THEN
        RAISE_APPLICATION_ERROR(-20602, 'El lote no corresponde al tipo de combustible del tanque');
    END IF;
    IF V_SALDO + P_LITROS > V_CAPACIDAD THEN
        RAISE_APPLICATION_ERROR(-20603, 'La recepcion excede la capacidad del tanque');
    END IF;

    SELECT COUNT(*) INTO V_PERMISOS
      FROM ASIGNACION_ESTACION A
      JOIN USUARIO_SISTEMA U ON U.ID_USUARIO = A.ID_USUARIO
     WHERE A.ID_ESTACION = V_ID_ESTACION
       AND A.ID_USUARIO = P_ID_USUARIO
       AND U.ESTADO = 'ACTIVO'
       AND A.FECHA_INICIO <= TRUNC(SYSDATE)
       AND (A.FECHA_FIN IS NULL OR A.FECHA_FIN > TRUNC(SYSDATE));

    IF V_PERMISOS = 0 THEN
        RAISE_APPLICATION_ERROR(-20604, 'Usuario sin asignacion activa a la estacion');
    END IF;

    INSERT INTO RECEPCION_COMBUSTIBLE
      (ID_LOTE, ID_TANQUE, ID_USUARIO, LITROS_RECIBIDOS, NUMERO_DOCUMENTO)
    VALUES
      (P_ID_LOTE, P_ID_TANQUE, P_ID_USUARIO, P_LITROS, TRIM(P_NUM_DOCUMENTO));

    UPDATE TANQUE_ESTACION
       SET SALDO_ESTIMADO_L = SALDO_ESTIMADO_L + P_LITROS
     WHERE ID_TANQUE = P_ID_TANQUE;

EXCEPTION
    WHEN DUP_VAL_ON_INDEX THEN
        RAISE_APPLICATION_ERROR(-20605, 'El documento de recepcion ya existe');
    WHEN NO_DATA_FOUND THEN
        RAISE_APPLICATION_ERROR(-20606, 'Lote o tanque inexistente');
END PRC_M2_REGISTRAR_RECEPCION;
/
SHOW ERRORS PROCEDURE PRC_M2_REGISTRAR_RECEPCION;
