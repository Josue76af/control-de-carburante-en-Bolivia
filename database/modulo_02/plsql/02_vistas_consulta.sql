CREATE OR REPLACE VIEW V_M2_PRECIO_VIGENTE AS
SELECT ID_PRECIO, ID_COMBUSTIBLE, TARIFA, PRECIO_LITRO,
       VIGENCIA_DESDE, VIGENCIA_HASTA
FROM (
    SELECT PC.*,
           ROW_NUMBER() OVER (
               PARTITION BY ID_COMBUSTIBLE, TARIFA
               ORDER BY VIGENCIA_DESDE DESC, ID_PRECIO DESC
           ) AS RN
      FROM PRECIO_COMBUSTIBLE PC
     WHERE PC.VIGENCIA_DESDE <= TRUNC(SYSDATE)
       AND (PC.VIGENCIA_HASTA IS NULL OR PC.VIGENCIA_HASTA > TRUNC(SYSDATE))
)
WHERE RN = 1;

CREATE OR REPLACE VIEW V_M2_BALANCE_TANQUES AS
SELECT E.ID_ESTACION, E.CODIGO AS COD_ESTACION,
       E.NOMBRE AS ESTACION,
       T.ID_TANQUE, T.CODIGO AS COD_TANQUE,
       C.CODIGO AS COMBUSTIBLE,
       T.CAPACIDAD_MAX_L, T.SALDO_ESTIMADO_L,
       NVL(R.LITROS_RECIBIDOS, 0) AS RECEPCIONES_ACUMULADAS_L,
       NVL(R.LITROS_RECIBIDOS, 0) - T.SALDO_ESTIMADO_L AS DIF_RECEPCION_VS_SALDO_L
  FROM TANQUE_ESTACION T
  JOIN ESTACION_SERVICIO E ON E.ID_ESTACION = T.ID_ESTACION
  JOIN TIPO_COMBUSTIBLE C ON C.ID_COMBUSTIBLE = T.ID_COMBUSTIBLE
  LEFT JOIN (
     SELECT ID_TANQUE, SUM(LITROS_RECIBIDOS) AS LITROS_RECIBIDOS
       FROM RECEPCION_COMBUSTIBLE GROUP BY ID_TANQUE
  ) R ON R.ID_TANQUE = T.ID_TANQUE;

