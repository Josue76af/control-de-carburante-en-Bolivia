SELECT ID_TANQUE, SALDO_ESTIMADO_L, CAPACIDAD_MAX_L
  FROM TANQUE_ESTACION WHERE SALDO_ESTIMADO_L>CAPACIDAD_MAX_L;
PROMPT Esperado: 0 filas.
