SET SERVEROUTPUT ON;
PROMPT === A. Verificar que existan las 12 tablas M2 ===
SELECT TABLE_NAME FROM USER_TABLES
 WHERE TABLE_NAME IN (
 'PERFIL_CONSUMO','PRECIO_COMBUSTIBLE','ESTACION_SERVICIO','SURTIDOR',
 'TANQUE_ESTACION','MANGUERA','USUARIO_SISTEMA','ROL','USUARIO_ROL',
 'ASIGNACION_ESTACION','LOTE_COMBUSTIBLE','RECEPCION_COMBUSTIBLE')
 ORDER BY TABLE_NAME;
PROMPT Esperado: 12 filas (ademas de las 7 tablas M1).

PROMPT === B. Comprobar que vistas y procedimiento fueron compilados ===
SELECT OBJECT_NAME, OBJECT_TYPE, STATUS FROM USER_OBJECTS
 WHERE OBJECT_NAME IN ('PRC_M2_REGISTRAR_RECEPCION','V_M2_PRECIO_VIGENTE','V_M2_BALANCE_TANQUES')
 ORDER BY OBJECT_NAME;
PROMPT Esperado: 3 objetos VALID.

PROMPT === C. Mostrar errores de compilacion, si hay ===
SELECT NAME, TYPE, LINE, POSITION, TEXT FROM USER_ERRORS
 WHERE NAME IN ('PRC_M2_REGISTRAR_RECEPCION','V_M2_PRECIO_VIGENTE','V_M2_BALANCE_TANQUES')
 ORDER BY NAME, SEQUENCE;

PROMPT === D. Conteos de registros DEMO ===
SELECT 'ESTACIONES' AS OBJETO, COUNT(*) AS TOTAL FROM ESTACION_SERVICIO WHERE CODIGO LIKE 'DEMO-ES-%'
UNION ALL
SELECT 'SURTIDORES', COUNT(*) FROM SURTIDOR WHERE ID_ESTACION IN (SELECT ID_ESTACION FROM ESTACION_SERVICIO WHERE CODIGO LIKE 'DEMO-ES-%')
UNION ALL
SELECT 'TANQUES', COUNT(*) FROM TANQUE_ESTACION WHERE ID_ESTACION IN (SELECT ID_ESTACION FROM ESTACION_SERVICIO WHERE CODIGO LIKE 'DEMO-ES-%')
UNION ALL
SELECT 'MANGUERAS', COUNT(*) FROM MANGUERA WHERE ID_SURTIDOR IN
  (SELECT S.ID_SURTIDOR FROM SURTIDOR S JOIN ESTACION_SERVICIO E ON E.ID_ESTACION=S.ID_ESTACION WHERE E.CODIGO LIKE 'DEMO-ES-%')
UNION ALL
SELECT 'RECEPCIONES', COUNT(*) FROM RECEPCION_COMBUSTIBLE WHERE NUMERO_DOCUMENTO LIKE 'DEMO-REC-%';
PROMPT Esperado: 20, 20, 40, 40, 40 con demo en esquema limpio.

PROMPT === E. Recepciones que no coinciden con el combustible de su tanque ===
SELECT R.ID_RECEPCION, R.NUMERO_DOCUMENTO
  FROM RECEPCION_COMBUSTIBLE R
  JOIN LOTE_COMBUSTIBLE L ON L.ID_LOTE=R.ID_LOTE
  JOIN TANQUE_ESTACION T ON T.ID_TANQUE=R.ID_TANQUE
 WHERE L.ID_COMBUSTIBLE <> T.ID_COMBUSTIBLE;
PROMPT Esperado: 0 filas en registros insertados por procedimiento.

