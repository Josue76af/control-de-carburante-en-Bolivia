PROMPT === 1. Cantidad de estaciones sinteticas ===
SELECT COUNT(*) AS ESTACIONES_DEMO
  FROM ESTACION_SERVICIO WHERE CODIGO LIKE 'DEMO-ES-%';

PROMPT === 2. Estaciones, surtidores y mangueras ===
SELECT E.CODIGO AS ESTACION, S.CODIGO AS SURTIDOR,
       M.CODIGO AS MANGUERA, C.CODIGO AS COMBUSTIBLE
  FROM ESTACION_SERVICIO E
  JOIN SURTIDOR S ON S.ID_ESTACION=E.ID_ESTACION
  JOIN MANGUERA M ON M.ID_SURTIDOR=S.ID_SURTIDOR
  JOIN TANQUE_ESTACION T ON T.ID_TANQUE=M.ID_TANQUE
  JOIN TIPO_COMBUSTIBLE C ON C.ID_COMBUSTIBLE=T.ID_COMBUSTIBLE
 WHERE E.CODIGO LIKE 'DEMO-ES-%'
 ORDER BY E.CODIGO, S.CODIGO, M.CODIGO;

PROMPT === 3. Inventario por estacion y combustible ===
SELECT COD_ESTACION, COMBUSTIBLE, CAPACIDAD_MAX_L,
       SALDO_ESTIMADO_L, RECEPCIONES_ACUMULADAS_L
  FROM V_M2_BALANCE_TANQUES
 WHERE COD_ESTACION LIKE 'DEMO-ES-%'
 ORDER BY COD_ESTACION, COMBUSTIBLE;

PROMPT === 4. Precios vigentes - solo datos de prueba, NO valores oficiales ===
SELECT C.CODIGO AS COMBUSTIBLE, P.TARIFA, P.PRECIO_LITRO,
       P.VIGENCIA_DESDE
  FROM V_M2_PRECIO_VIGENTE P
  JOIN TIPO_COMBUSTIBLE C ON C.ID_COMBUSTIBLE=P.ID_COMBUSTIBLE
 ORDER BY C.CODIGO, P.TARIFA;

PROMPT === 5. Totales por tipo de combustible (GROUP BY) ===
SELECT C.CODIGO AS COMBUSTIBLE,
       COUNT(T.ID_TANQUE) AS CANT_TANQUES,
       SUM(T.CAPACIDAD_MAX_L) AS CAPACIDAD_TOTAL_L,
       SUM(T.SALDO_ESTIMADO_L) AS SALDO_TOTAL_L
  FROM TANQUE_ESTACION T
  JOIN TIPO_COMBUSTIBLE C ON C.ID_COMBUSTIBLE=T.ID_COMBUSTIBLE
  JOIN ESTACION_SERVICIO E ON E.ID_ESTACION=T.ID_ESTACION
 WHERE E.CODIGO LIKE 'DEMO-ES-%'
 GROUP BY C.CODIGO
 ORDER BY C.CODIGO;

PROMPT === 6. Recepciones y sus responsables (JOIN multiple) ===
SELECT E.CODIGO AS ESTACION, RC.NUMERO_DOCUMENTO,
       TC.CODIGO AS COMBUSTIBLE, RC.LITROS_RECIBIDOS,
       U.USUARIO AS OPERADOR, RC.FECHA_HORA
  FROM RECEPCION_COMBUSTIBLE RC
  JOIN TANQUE_ESTACION T ON T.ID_TANQUE=RC.ID_TANQUE
  JOIN ESTACION_SERVICIO E ON E.ID_ESTACION=T.ID_ESTACION
  JOIN LOTE_COMBUSTIBLE L ON L.ID_LOTE=RC.ID_LOTE
  JOIN TIPO_COMBUSTIBLE TC ON TC.ID_COMBUSTIBLE=L.ID_COMBUSTIBLE
  JOIN USUARIO_SISTEMA U ON U.ID_USUARIO=RC.ID_USUARIO
 WHERE RC.NUMERO_DOCUMENTO LIKE 'DEMO-REC-%'
 ORDER BY E.CODIGO, RC.NUMERO_DOCUMENTO;

PROMPT === 7. Usuarios, roles y estaciones asignadas ===
SELECT U.USUARIO, R.NOMBRE AS ROL,
       COUNT(DISTINCT A.ID_ESTACION) AS ESTACIONES_ASIGNADAS
  FROM USUARIO_SISTEMA U
  JOIN USUARIO_ROL UR ON UR.ID_USUARIO=U.ID_USUARIO
  JOIN ROL R ON R.ID_ROL=UR.ID_ROL
  LEFT JOIN ASIGNACION_ESTACION A ON A.ID_USUARIO=U.ID_USUARIO
 WHERE U.USUARIO LIKE 'demo_%_m2'
 GROUP BY U.USUARIO, R.NOMBRE;

PROMPT === 8. Integracion con M1: propietario y cantidad de vehiculos ===
SELECT P.ID_PERSONA, P.CI, P.NOMBRES,
       COUNT(V.ID_VEHICULO) AS TOTAL_VEHICULOS
  FROM PERSONA P
  LEFT JOIN VEHICULO V ON V.ID_PERSONA=P.ID_PERSONA
 GROUP BY P.ID_PERSONA,P.CI,P.NOMBRES
 ORDER BY TOTAL_VEHICULOS DESC, P.ID_PERSONA
 FETCH FIRST 20 ROWS ONLY;

PROMPT === 9. Estaciones con mas de un tanque (HAVING) ===
SELECT E.CODIGO, COUNT(T.ID_TANQUE) AS TANQUES
  FROM ESTACION_SERVICIO E
  JOIN TANQUE_ESTACION T ON T.ID_ESTACION=E.ID_ESTACION
 WHERE E.CODIGO LIKE 'DEMO-ES-%'
 GROUP BY E.CODIGO HAVING COUNT(T.ID_TANQUE)>1
 ORDER BY E.CODIGO;

PROMPT === 10. Ranking de recepciones por estacion (funcion analitica) ===
SELECT E.CODIGO, SUM(R.LITROS_RECIBIDOS) AS TOTAL_LITROS,
       DENSE_RANK() OVER (ORDER BY SUM(R.LITROS_RECIBIDOS) DESC) AS RANK_LITROS
  FROM RECEPCION_COMBUSTIBLE R
  JOIN TANQUE_ESTACION T ON T.ID_TANQUE=R.ID_TANQUE
  JOIN ESTACION_SERVICIO E ON E.ID_ESTACION=T.ID_ESTACION
 WHERE R.NUMERO_DOCUMENTO LIKE 'DEMO-REC-%'
 GROUP BY E.CODIGO ORDER BY RANK_LITROS, E.CODIGO;
