-- Pruebas de validacion del procedimiento: no debe crear registros.
-- Ejecutar con F5 DESPUES de cargar datos demo. Las excepciones esperadas se capturan.
SET SERVEROUTPUT ON;
DECLARE
  V_TG NUMBER;
  V_LOTE_G NUMBER;
  V_LOTE_D NUMBER;
  V_USUARIO NUMBER;
  V_ERR NUMBER;
BEGIN
  SELECT T.ID_TANQUE INTO V_TG FROM TANQUE_ESTACION T
  JOIN ESTACION_SERVICIO E ON E.ID_ESTACION=T.ID_ESTACION
  WHERE E.CODIGO='DEMO-ES-01' AND T.CODIGO='TG01';
  SELECT ID_LOTE INTO V_LOTE_G FROM LOTE_COMBUSTIBLE WHERE CODIGO_LOTE='DEMO-LOTE-G';
  SELECT ID_LOTE INTO V_LOTE_D FROM LOTE_COMBUSTIBLE WHERE CODIGO_LOTE='DEMO-LOTE-D';
  SELECT ID_USUARIO INTO V_USUARIO FROM USUARIO_SISTEMA WHERE USUARIO='demo_operador_m2';

  -- Caso 1: rechazo por sobrecapacidad (error -20603).
  BEGIN
    PRC_M2_REGISTRAR_RECEPCION(V_LOTE_G,V_TG,V_USUARIO,999999,'DEMO-RECHAZADA-CAPACIDAD');
    RAISE_APPLICATION_ERROR(-20901,'FALLO: permitio sobrecapacidad');
  EXCEPTION WHEN OTHERS THEN
    V_ERR:=SQLCODE;
    IF V_ERR = -20603 THEN DBMS_OUTPUT.PUT_LINE('OK sobrecapacidad rechazada (-20603)');
    ELSE RAISE; END IF;
  END;

  -- Caso 2: rechazo por mezcla diesel/gasolina (error -20602).
  BEGIN
    PRC_M2_REGISTRAR_RECEPCION(V_LOTE_D,V_TG,V_USUARIO,1,'DEMO-RECHAZADA-COMBUSTIBLE');
    RAISE_APPLICATION_ERROR(-20902,'FALLO: permitio lote incompatible');
  EXCEPTION WHEN OTHERS THEN
    V_ERR:=SQLCODE;
    IF V_ERR = -20602 THEN DBMS_OUTPUT.PUT_LINE('OK tipo incompatible rechazado (-20602)');
    ELSE RAISE; END IF;
  END;
END;
/
