-- Tabla: PRECIO_COMBUSTIBLE. 
 ID_PRECIO NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
 ID_COMBUSTIBLE NUMBER(4) NOT NULL,
 TARIFA VARCHAR2(20 CHAR) NOT NULL,
 PRECIO_LITRO NUMBER(10,2) NOT NULL,
 VIGENCIA_DESDE DATE NOT NULL,
 VIGENCIA_HASTA DATE,
 CONSTRAINT PK_PRECIO PRIMARY KEY (ID_PRECIO),
 CONSTRAINT FK_PRECIO_COMB FOREIGN KEY (ID_COMBUSTIBLE) REFERENCES TIPO_COMBUSTIBLE(ID_COMBUSTIBLE),
 CONSTRAINT UQ_PRECIO_INICIO UNIQUE (ID_COMBUSTIBLE,TARIFA,VIGENCIA_DESDE),
 CONSTRAINT CK_PRECIO_TARIFA CHECK (TARIFA IN ('SUBVENCIONADO','INTERNACIONAL')),
 CONSTRAINT CK_PRECIO_VAL CHECK (PRECIO_LITRO > 0),
 CONSTRAINT CK_PRECIO_FECHA CHECK (VIGENCIA_HASTA IS NULL OR VIGENCIA_HASTA > VIGENCIA_DESDE)
);

CREATE INDEX IX_PRECIO_COMB ON PRECIO_COMBUSTIBLE(ID_COMBUSTIBLE,TARIFA,VIGENCIA_DESDE);
