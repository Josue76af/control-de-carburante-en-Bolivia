-- Tabla: ESTACION_SERVICIO. 
CREATE TABLE ESTACION_SERVICIO (
 ID_ESTACION NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
 CODIGO VARCHAR2(30 CHAR) NOT NULL,
 NOMBRE VARCHAR2(100 CHAR) NOT NULL,
 DEPARTAMENTO VARCHAR2(60 CHAR) NOT NULL,
 MUNICIPIO VARCHAR2(80 CHAR) NOT NULL,
 DIRECCION VARCHAR2(250 CHAR),
 LATITUD NUMBER(10,7) NOT NULL,
 LONGITUD NUMBER(10,7) NOT NULL,
 ESTADO VARCHAR2(15 CHAR) DEFAULT 'ACTIVA' NOT NULL,
 CONSTRAINT PK_ESTACION PRIMARY KEY (ID_ESTACION),
 CONSTRAINT UQ_ESTACION_COD UNIQUE (CODIGO),
 CONSTRAINT CK_ESTACION_LAT CHECK (LATITUD BETWEEN -90 AND 90),
 CONSTRAINT CK_ESTACION_LONG CHECK (LONGITUD BETWEEN -180 AND 180),
 CONSTRAINT CK_ESTACION_EST CHECK (ESTADO IN ('ACTIVA','INACTIVA','BLOQUEADA'))
);


