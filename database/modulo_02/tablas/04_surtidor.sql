-- Tabla: SURTIDOR. 
 ID_SURTIDOR NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
 ID_ESTACION NUMBER(12) NOT NULL,
 CODIGO VARCHAR2(30 CHAR) NOT NULL,
 ESTADO VARCHAR2(15 CHAR) DEFAULT 'ACTIVO' NOT NULL,
 CONSTRAINT PK_SURTIDOR PRIMARY KEY (ID_SURTIDOR),
 CONSTRAINT FK_SURT_ESTACION FOREIGN KEY (ID_ESTACION) REFERENCES ESTACION_SERVICIO(ID_ESTACION),
 CONSTRAINT UQ_SURT_ESTACION UNIQUE (ID_ESTACION,CODIGO),
 CONSTRAINT CK_SURT_EST CHECK (ESTADO IN ('ACTIVO','INACTIVO','MANTENIMIENTO'))
);

CREATE INDEX IX_M2_SURT_EST ON SURTIDOR(ID_ESTACION);
