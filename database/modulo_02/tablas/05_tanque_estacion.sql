-- Tabla: TANQUE_ESTACION. 
 ID_TANQUE NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
 ID_ESTACION NUMBER(12) NOT NULL,
 ID_COMBUSTIBLE NUMBER(4) NOT NULL,
 CODIGO VARCHAR2(30 CHAR) NOT NULL,
 CAPACIDAD_MAX_L NUMBER(12,2) NOT NULL,
 SALDO_ESTIMADO_L NUMBER(12,2) DEFAULT 0 NOT NULL,
 ESTADO VARCHAR2(15 CHAR) DEFAULT 'ACTIVO' NOT NULL,
 CONSTRAINT PK_TANQUE PRIMARY KEY (ID_TANQUE),
 CONSTRAINT FK_TANQUE_EST FOREIGN KEY (ID_ESTACION) REFERENCES ESTACION_SERVICIO(ID_ESTACION),
 CONSTRAINT FK_TANQUE_COMB FOREIGN KEY (ID_COMBUSTIBLE) REFERENCES TIPO_COMBUSTIBLE(ID_COMBUSTIBLE),
 CONSTRAINT UQ_TANQUE_COD UNIQUE (ID_ESTACION,CODIGO),
 CONSTRAINT CK_TANQUE_CAP CHECK (CAPACIDAD_MAX_L > 0),
 CONSTRAINT CK_TANQUE_SALDO CHECK (SALDO_ESTIMADO_L BETWEEN 0 AND CAPACIDAD_MAX_L),
 CONSTRAINT CK_TANQUE_EST CHECK (ESTADO IN ('ACTIVO','INACTIVO','MANTENIMIENTO'))
);

CREATE INDEX IX_M2_TANQUE_EST ON TANQUE_ESTACION(ID_ESTACION);
CREATE INDEX IX_M2_TANQUE_COMB ON TANQUE_ESTACION(ID_COMBUSTIBLE);
