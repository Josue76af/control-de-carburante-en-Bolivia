-- Tabla: MANGUERA. No modificar ni recrear las 7 tablas iniciales.
CREATE TABLE MANGUERA (
 ID_MANGUERA NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
 ID_SURTIDOR NUMBER(12) NOT NULL,
 ID_TANQUE NUMBER(12) NOT NULL,
 CODIGO VARCHAR2(30 CHAR) NOT NULL,
 ESTADO VARCHAR2(15 CHAR) DEFAULT 'ACTIVA' NOT NULL,
 CONSTRAINT PK_MANGUERA PRIMARY KEY (ID_MANGUERA),
 CONSTRAINT FK_MANG_SURT FOREIGN KEY (ID_SURTIDOR) REFERENCES SURTIDOR(ID_SURTIDOR),
 CONSTRAINT FK_MANG_TANQUE FOREIGN KEY (ID_TANQUE) REFERENCES TANQUE_ESTACION(ID_TANQUE),
 CONSTRAINT UQ_MANG_COD UNIQUE (ID_SURTIDOR,CODIGO),
 CONSTRAINT CK_MANG_EST CHECK (ESTADO IN ('ACTIVA','INACTIVA','MANTENIMIENTO'))
);

CREATE INDEX IX_MANG_TANQUE ON MANGUERA(ID_TANQUE);
CREATE INDEX IX_M2_MANG_SURT ON MANGUERA(ID_SURTIDOR);
