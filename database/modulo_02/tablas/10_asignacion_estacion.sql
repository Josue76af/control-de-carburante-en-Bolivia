-- Tabla: ASIGNACION_ESTACION. No modificar ni recrear las 7 tablas iniciales.
CREATE TABLE ASIGNACION_ESTACION (
 ID_ASIGNACION NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
 ID_USUARIO NUMBER(12) NOT NULL,
 ID_ESTACION NUMBER(12) NOT NULL,
 FECHA_INICIO DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
 FECHA_FIN DATE,
 CONSTRAINT PK_ASIGNACION PRIMARY KEY (ID_ASIGNACION),
 CONSTRAINT FK_ASIG_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO_SISTEMA(ID_USUARIO),
 CONSTRAINT FK_ASIG_ESTACION FOREIGN KEY (ID_ESTACION) REFERENCES ESTACION_SERVICIO(ID_ESTACION),
 CONSTRAINT CK_ASIG_FECHA CHECK (FECHA_FIN IS NULL OR FECHA_FIN > FECHA_INICIO)
);

CREATE INDEX IX_USR_ASIG ON ASIGNACION_ESTACION(ID_USUARIO,ID_ESTACION);
CREATE INDEX IX_M2_ASIG_EST ON ASIGNACION_ESTACION(ID_ESTACION);
