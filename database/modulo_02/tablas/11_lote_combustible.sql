-- Tabla: LOTE_COMBUSTIBLE. No modificar ni recrear las 7 tablas iniciales.
CREATE TABLE LOTE_COMBUSTIBLE (
 ID_LOTE NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
 ID_COMBUSTIBLE NUMBER(4) NOT NULL,
 CODIGO_LOTE VARCHAR2(60 CHAR) NOT NULL,
 PROVEEDOR VARCHAR2(120 CHAR),
 FECHA_LOTE DATE,
 CONSTRAINT PK_LOTE PRIMARY KEY (ID_LOTE),
 CONSTRAINT FK_LOTE_COMB FOREIGN KEY (ID_COMBUSTIBLE) REFERENCES TIPO_COMBUSTIBLE(ID_COMBUSTIBLE),
 CONSTRAINT UQ_LOTE_COD UNIQUE (CODIGO_LOTE)
);

CREATE INDEX IX_M2_LOTE_COMB ON LOTE_COMBUSTIBLE(ID_COMBUSTIBLE);
