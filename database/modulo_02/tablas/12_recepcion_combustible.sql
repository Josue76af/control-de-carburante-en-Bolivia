-- Tabla: RECEPCION_COMBUSTIBLE. No modificar ni recrear las 7 tablas iniciales.
CREATE TABLE RECEPCION_COMBUSTIBLE (
 ID_RECEPCION NUMBER(12) GENERATED BY DEFAULT ON NULL AS IDENTITY,
 ID_LOTE NUMBER(12) NOT NULL,
 ID_TANQUE NUMBER(12) NOT NULL,
 ID_USUARIO NUMBER(12) NOT NULL,
 LITROS_RECIBIDOS NUMBER(12,2) NOT NULL,
 NUMERO_DOCUMENTO VARCHAR2(80 CHAR) NOT NULL,
 FECHA_HORA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT PK_RECEPCION PRIMARY KEY (ID_RECEPCION),
 CONSTRAINT FK_RECEP_LOTE FOREIGN KEY (ID_LOTE) REFERENCES LOTE_COMBUSTIBLE(ID_LOTE),
 CONSTRAINT FK_RECEP_TANQUE FOREIGN KEY (ID_TANQUE) REFERENCES TANQUE_ESTACION(ID_TANQUE),
 CONSTRAINT FK_RECEP_USER FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO_SISTEMA(ID_USUARIO),
 CONSTRAINT UQ_RECEP_DOC UNIQUE (NUMERO_DOCUMENTO),
 CONSTRAINT CK_RECEP_LITROS CHECK (LITROS_RECIBIDOS > 0)
);

CREATE INDEX IX_RECEP_TANQUE ON RECEPCION_COMBUSTIBLE(ID_TANQUE,FECHA_HORA);
